// Run with: node --experimental-transform-types tests/npc-facing.mjs
import assert from "node:assert/strict";
import { Matrix, NullEngine, Scene, TransformNode, Vector3 } from "@babylonjs/core";
import { NpcFacing } from "../src/world/NpcFacing.ts";
const engine = new NullEngine(), scene = new Scene(engine);
const parent = new TransformNode("world", scene), anchor = new TransformNode("npc", scene);
anchor.parent = parent; anchor.rotation.y = 0.3;
const facing = new NpcFacing(anchor);
const step = (players, frames = 120) => { for (let i = 0; i < frames; i++) facing.update(players, 1 / 60); };
const angleError = (a, b) => Math.abs(Math.atan2(Math.sin(a - b), Math.cos(a - b)));
step([{ id: 1, position: new Vector3(8, 0, 0) }]);
assert.ok(angleError(anchor.rotation.y, 0.3) < 0.001, "distant player must not activate NPC");
const player = { id: 1, position: new Vector3(3, 0, 0) };
facing.update([player], 1 / 60);
assert.ok(anchor.rotation.y > 0.3 && anchor.rotation.y < Math.PI / 2, "turn should be smooth");
step([player]);
assert.ok(angleError(anchor.rotation.y, Math.PI / 2) < 0.002, "NPC must face nearby player");
step([{ ...player, position: new Vector3(4.9, 0, 0) }]);
assert.ok(angleError(anchor.rotation.y, Math.PI / 2) < 0.002, "leaving range must have hysteresis");
step([{ ...player, position: new Vector3(6, 0, 0) }]);
assert.ok(angleError(anchor.rotation.y, 0.3) < 0.002, "NPC must return to initial facing");
step([{ id: 1, position: new Vector3(0, 0, 3) }, { id: 2, position: new Vector3(-2, 0, 0) }]);
assert.ok(angleError(anchor.rotation.y, -Math.PI / 2) < 0.002, "NPC must face the nearest player");
step([{ id: 1, position: new Vector3(0, 0, 1.8) }, { id: 2, position: new Vector3(-2, 0, 0) }]);
assert.ok(angleError(anchor.rotation.y, -Math.PI / 2) < 0.002, "near-ties should not switch targets");
anchor.rotation.y = Math.PI - 0.05;
step([{ id: 2, position: new Vector3(-0.1, 0, -2) }], 1);
assert.ok(anchor.rotation.y > 3, "turn must use the short route across the angular boundary");
parent.rotation.y = Math.PI / 2; parent.computeWorldMatrix(true);
const target = new Vector3(0, 0, 3);
const local = Vector3.TransformCoordinates(target, Matrix.Invert(parent.getWorldMatrix()));
step([{ id: 3, position: target }]);
assert.ok(angleError(anchor.rotation.y, Math.atan2(local.x, local.z)) < 0.002, "parent rotation must be respected");
step([{ id: 3, position: Vector3.Zero() }]);
assert.ok(Number.isFinite(anchor.rotation.y), "overlapping positions must not produce NaN");
scene.dispose(); engine.dispose();
console.log("NPC facing: proximity, multiple players, wraparound and parent transforms OK");
